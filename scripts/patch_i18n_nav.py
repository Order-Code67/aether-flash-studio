def patch(path: Path, extra: str) -> None:
    text = path.read_text(encoding="utf-8")
    if '"nav.flash_manager"' in text:
        print(f"skip {path.name}")
        return
    # insert before closing };
    idx = text.rfind("};")
    if idx < 0:
        raise SystemExit(f"no end in {path}")
    # ensure previous entry ends with comma
    head = text[:idx].rstrip()
    if not head.endswith(","):
        head += ","
    path.write_text(head + "\n" + extra.rstrip() + "\n};\n", encoding="utf-8")
    print(f"patched {path.name}")


